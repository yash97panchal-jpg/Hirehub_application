/**
 * Returns the authentic company logo symbol.
 * Falls back to extracting domain from website or using crisp official favicon services.
 */
export function getCompanyRealLogo(
  nameOrSlug: string,
  website?: string,
  existingLogo?: string
): string {
  // If already a valid non-Unsplash URL (e.g. SVG, favicon, data URL), use it
  if (
    existingLogo &&
    !existingLogo.includes("images.unsplash.com") &&
    (existingLogo.startsWith("http") || existingLogo.startsWith("data:image") || existingLogo.startsWith("/"))
  ) {
    return existingLogo
  }

  const key = (nameOrSlug || "").toLowerCase().replace(/[^a-z0-9]/g, "")

  for (const [k, url] of Object.entries(OFFICIAL_COMPANY_LOGOS)) {
    const cleanK = k.replace(/[^a-z0-9]/g, "")
    if (key.includes(cleanK) || cleanK.includes(key)) {
      return url
    }
  }

  // Derive domain from website if available
  if (website) {
    try {
      const parsed = new URL(website.startsWith("http") ? website : `https://${website}`)
      const host = parsed.hostname.replace(/^www\./, "")
      return `https://www.google.com/s2/favicons?domain=${host}&sz=128`
    } catch {
      // ignore
    }
  }

  return "https://www.google.com/s2/favicons?domain=google.com&sz=128"
}
